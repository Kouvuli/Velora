#!/usr/bin/env python3
"""AI Skill OS hook dispatcher (copied into each project as .ai/hooks/run.py).

Standalone on purpose: Python 3 standard library only, no `ai-skills` install
needed, so the same guards run locally, in CI and in cloud agents.

    python3 .ai/hooks/run.py <trigger> [--format plain|git|claude] [files...]

Triggers: pre-commit | post-edit | pre-tool:shell | pre-delivery | stop (the agent is about to finish its turn)
Canonical exit codes (--format plain): 0 pass, 1 block, 2 warn.
--format git     : block -> 1, warn -> 0 (git only knows pass/fail)
--format claude|codex|gemini|cursor : reads the tool's hook JSON from stdin.
  claude         :
                   pre-tool:shell  block -> exit 2 (tool call blocked, reason shown),
                                   warn  -> JSON permissionDecision "ask" (user confirms)
                   post-edit       block/warn -> exit 2 (stderr fed back to Claude)
                   stop            block -> JSON decision "block" (Claude keeps working on the reason);
                                   the same failure blocks at most once per session, so it can never loop

A hook that crashes is reported as a warning, never a silent pass or a hard block.
Hooks are enabled in .ai/hooks/config.json (generated by `ai-skills`; edit via
`ai-skills hooks enable|disable`).
"""
from __future__ import annotations

import importlib.util
import json
import os
import re
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # no __pycache__ next to locked hooks (it would change their hash)
HERE = Path(__file__).resolve().parent
TRIGGERS = ("pre-commit", "post-edit", "pre-tool:shell", "pre-delivery", "stop")
MAX_BYTES = 1024 * 1024


def _git(root: Path, *args: str) -> str:
    try:
        r = subprocess.run(["git", *args], cwd=root, capture_output=True, timeout=30)
        return r.stdout.decode("utf-8", errors="replace") if r.returncode == 0 else ""
    except (OSError, subprocess.SubprocessError):
        return ""


TOOL_FORMATS = ("claude", "codex", "gemini", "cursor")
PATCH_FILE = re.compile(r"^\*\*\* (?:Add|Update) File: (.+)$", re.MULTILINE)


def _root() -> Path:
    for var in ("CLAUDE_PROJECT_DIR", "GEMINI_PROJECT_DIR"):
        if os.environ.get(var):
            return Path(os.environ[var]).resolve()
    return HERE.parents[1]  # <project>/.ai/hooks/run.py


class Context:
    """What a hook sees. Hooks only read; they never modify the project."""

    def __init__(self, trigger: str, root: Path, files, command=None, staged=False):
        self.trigger = trigger
        self.root = root
        self.files = [f for f in files if f]
        self.command = command
        self.staged = staged

    def read(self, rel: str) -> str:
        """File content as it will be committed (index) for pre-commit, else the working tree."""
        if self.staged:
            data = subprocess.run(["git", "show", f":{rel}"], cwd=self.root, capture_output=True).stdout
        else:
            p = self.root / rel
            try:
                if not p.is_file() or p.stat().st_size > MAX_BYTES:
                    return ""
                data = p.read_bytes()
            except OSError:
                return ""
        if b"\0" in data[:8192]:
            return ""  # binary
        return data[:MAX_BYTES].decode("utf-8", errors="replace")


def _load(name: str):
    path = HERE / name / "hook.py"
    spec = importlib.util.spec_from_file_location(f"ai_hook_{name.replace('-', '_')}", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _edited_paths(payload: dict):
    """File paths from any supported tool payload (Claude/Codex/Gemini tool_input, Cursor top level,
    Codex apply_patch text)."""
    ti = payload.get("tool_input") if isinstance(payload.get("tool_input"), dict) else {}
    out = [v for src in (ti, payload) for k in ("file_path", "path", "absolute_path")
           if isinstance((v := src.get(k)), str)]
    for v in list(ti.values()) + [payload.get("patch")]:
        if isinstance(v, str) and "*** " in v:
            out += PATCH_FILE.findall(v)
    return out


def _context(trigger: str, root: Path, files, payload: dict) -> Context:
    ti = payload.get("tool_input") if isinstance(payload.get("tool_input"), dict) else {}
    if trigger == "pre-tool:shell":
        cmd = ti.get("command") or payload.get("command") or " ".join(files)
        return Context(trigger, root, [], command=" ".join(cmd) if isinstance(cmd, list) else cmd)
    if trigger == "post-edit":
        rel = []
        for fp in _edited_paths(payload) or files:
            p = Path(fp) if Path(fp).is_absolute() else root / fp
            try:
                rel.append(p.resolve().relative_to(root).as_posix())
            except ValueError:
                pass  # outside the project: not ours to judge
        return Context(trigger, root, rel)
    if trigger == "pre-commit":
        out = _git(root, "diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z")
        return Context(trigger, root, files or out.split("\0"), staged=not files)
    if trigger == "stop":   # what this session changed: modified, staged and new files
        changed = _git(root, "diff", "HEAD", "--name-only", "-z").split("\0") + \
            _git(root, "ls-files", "--others", "--exclude-standard", "-z").split("\0")
        return Context(trigger, root, files or sorted({f for f in changed if f}))
    out = _git(root, "ls-files", "-z")  # pre-delivery: everything tracked
    return Context(trigger, root, files or out.split("\0"))


STATE = ".ai/hooks-state.json"   # outside .ai/hooks/ so the locked hook files never change


def _stop_seen_before(root: Path, payload: dict, report: str) -> bool:
    """True when this exact failure already blocked a stop in this session: report it, but let the agent stop.
    Independent of the tool's own loop flag, so a failing check can never keep an agent running forever."""
    import hashlib
    key = str(payload.get("session_id") or "no-session")
    digest = hashlib.sha256(report.encode("utf-8")).hexdigest()[:16]
    f = root / STATE
    try:
        state = json.loads(f.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        state = {}
    seen = state.setdefault("stop", {}).setdefault(key, [])
    if digest in seen:
        return True
    seen.append(digest)
    state["stop"] = {k: v[-20:] for k, v in list(state["stop"].items())[-20:]}
    try:
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(json.dumps(state), encoding="utf-8")
    except OSError:
        pass
    return False


def main(argv=None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    fmt = "plain"
    if "--format" in args:
        i = args.index("--format")
        fmt = args[i + 1]
        del args[i:i + 2]
    if not args or args[0] not in TRIGGERS:
        print(f"usage: run.py <{'|'.join(TRIGGERS)}> [--format plain|git|claude] [files...]", file=sys.stderr)
        return 0 if fmt in TOOL_FORMATS else 2
    trigger, files = args[0], args[1:]
    payload = {}
    if fmt in TOOL_FORMATS:
        try:
            payload = json.load(sys.stdin)
        except (ValueError, OSError):
            payload = {}
    root = _root()
    try:
        config = json.loads((HERE / "config.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        config = {"hooks": []}
    ctx = _context(trigger, root, files, payload)

    blocks, warns = [], []
    for name in config.get("hooks") or []:
        try:
            mod = _load(name)
            if trigger not in getattr(mod, "TRIGGERS", ()):
                continue
            for level, msg in mod.check(ctx) or []:
                (blocks if level == "block" else warns).append(f"[{name}] {msg}")
        except Exception as e:  # noqa: BLE001 - a broken hook must be visible, not fatal
            warns.append(f"[{name}] hook failed ({type(e).__name__}: {e}); check skipped")

    if not blocks and not warns:
        if fmt == "gemini":
            print("{}")  # Gemini expects JSON on stdout
        return 0
    report = "\n".join(["AI Skill OS hook " + ("BLOCKED" if blocks else "warning") + f" ({trigger}):"]
                       + [f"  BLOCK {m}" for m in blocks] + [f"  WARN  {m}" for m in warns])
    if fmt == "cursor":
        print(report, file=sys.stderr)
        if trigger == "pre-tool:shell":
            print(json.dumps({"permission": "deny" if blocks else "ask"}))
            return 2 if blocks else 0
        return 0  # afterFileEdit cannot undo the edit; the git pre-commit hook still blocks the commit
    if fmt in ("codex", "gemini"):
        print(report, file=sys.stderr)
        if fmt == "gemini" and not blocks:
            print("{}")
        return 2 if (blocks or trigger == "post-edit") else 0  # exit 2: block, or feed the finding back
    if fmt == "claude" and trigger == "stop":
        if blocks and not _stop_seen_before(root, payload, report):
            print(json.dumps({"decision": "block", "reason": report + "\nFix these before finishing, or say why "
                              "they cannot be fixed now."}))
        else:
            print(json.dumps({"hookSpecificOutput": {"hookEventName": "Stop", "additionalContext": report}}))
        return 0
    if fmt == "claude":
        if trigger == "pre-tool:shell" and not blocks:
            print(json.dumps({"hookSpecificOutput": {"hookEventName": "PreToolUse", "permissionDecision": "ask",
                                                     "permissionDecisionReason": report}}))
            return 0
        print(report, file=sys.stderr)
        return 2
    print(report, file=sys.stderr)
    if blocks:
        if trigger == "pre-commit":
            print("Fix the problem, or (if it is a false positive) add `ai-skills: allow` on that line "
                  "or disable the hook with `ai-skills hooks disable <name>`.", file=sys.stderr)
        return 1
    return 0 if fmt == "git" else 2


if __name__ == "__main__":
    sys.exit(main())
